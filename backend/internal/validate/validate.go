// Package validate contains small domain-neutral validation helpers.
package validate

import "strings"

// StringList trims entries, drops empties and removes duplicates while
// preserving the original order.
func StringList(values []string) []string {
	out := make([]string, 0, len(values))
	seen := make(map[string]struct{}, len(values))
	for _, v := range values {
		v = strings.TrimSpace(v)
		if v == "" {
			continue
		}
		if _, ok := seen[v]; ok {
			continue
		}
		seen[v] = struct{}{}
		out = append(out, v)
	}
	return out
}
